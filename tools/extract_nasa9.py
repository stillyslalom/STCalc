#!/usr/bin/env python3
"""Extract NASA-9 polynomial fits from the NASA CEA thermodynamic database
(thermo.inp) into js/nasa9-data.js and data/nasa9-species.js.

    python3 tools/extract_nasa9.py /path/to/thermo.inp

thermo.inp is distributed with NASA CEA (Apache License 2.0); a copy is
bundled with CompactLES.jl under data/. The record format is fixed-column
Fortran: see NASA TP-2002-211556.
"""
import json
import sys

# Species the built-in gas list needs at page load (js/nasa9-data.js). Every
# neutral gaseous species goes into data/nasa9-species.js, loaded on demand
# for the species search.
BUILT_IN = ['Ar', 'He', 'Ne', 'Kr', 'Xe', 'N2', 'O2', 'H2', 'CO2', 'CH4', 'SF6', 'C3H6O,acetone']

HEADER = """/**
 * NASA-9 polynomial fits of ideal-gas thermodynamic functions%s.
 * GENERATED by tools/extract_nasa9.py from the NASA CEA database thermo.inp;
 * do not edit by hand.
 *
 * Source: NASA CEA (Chemical Equilibrium with Applications), Apache License
 * 2.0. See data/NASA_CEA_NOTICE.txt and data/NASA_CEA_LICENSE.txt.
 * Format: McBride, Zehe & Gordon, NASA TP-2002-211556.
 *
 *   cp/R  = a1/T^2 + a2/T + a3 + a4 T + a5 T^2 + a6 T^3 + a7 T^4
 *   h/RT  = -a1/T^2 + a2 ln(T)/T + a3 + a4 T/2 + a5 T^2/3 + a6 T^3/4 + a7 T^4/5 + b1/T
 *   s/R   = -a1/(2T^2) - a2/T + a3 ln(T) + a4 T + a5 T^2/2 + a6 T^3/3 + a7 T^4/4 + b2
 *
 * mw is in g/mol, temperatures in K.
 */
"""


def number(field):
    return float(field.strip().replace('D', 'E').replace('d', 'e'))


def parse(path):
    """All neutral gaseous species with at least one fitted interval."""
    lines = open(path, encoding='latin-1').read().splitlines()
    found = {}
    i = 0
    while i < len(lines) - 1:
        line = lines[i]
        header = lines[i + 1]
        # A record starts with a name line followed by a header whose first
        # two columns hold the number of temperature intervals
        is_record = (line[:1].strip() and not line.startswith('!') and len(header) >= 65
                     and header[0:2].strip().isdigit() and header[50:52].strip().isdigit())
        if not is_record:
            i += 1
            continue
        name = line[:16].strip()
        count = int(header[0:2])
        gaseous = int(header[50:52]) == 0
        neutral = not (name.endswith('+') or name.endswith('-'))
        if count > 0 and gaseous and neutral and name not in found:
            intervals = []
            for k in range(count):
                bounds, c1, c2 = lines[i + 2 + 3 * k: i + 5 + 3 * k]
                a = [number(c1[16 * j:16 * (j + 1)]) for j in range(5)]
                a += [number(c2[0:16]), number(c2[16:32])]
                intervals.append({
                    'Tmin': number(bounds[0:11]), 'Tmax': number(bounds[11:22]),
                    'a': a, 'b1': number(c2[48:64]), 'b2': number(c2[64:80]),
                })
            found[name] = {'mw': number(header[52:65]), 'intervals': intervals}
        i += 2 + 3 * count
    return found


def write(path, variable, suffix, data, export):
    body = ',\n'.join('    ' + json.dumps(name) + ': ' + json.dumps(record, separators=(',', ':'))
                      for name, record in data.items())
    with open(path, 'w') as out:
        out.write(HEADER % suffix)
        out.write('const %s = {\n%s\n};\n' % (variable, body))
        if export:
            out.write("\nif (typeof module !== 'undefined' && module.exports) {\n"
                      "    module.exports = { %s };\n}\n" % variable)
    print('wrote', path, 'with', len(data), 'species')


def main():
    data = parse(sys.argv[1])
    missing = [s for s in BUILT_IN if s not in data]
    if missing:
        sys.exit('species not found: ' + ', '.join(missing))
    write('js/nasa9-data.js', 'NASA9_DATA', ' for the built-in gases',
          {name: data[name] for name in BUILT_IN}, True)
    write('data/nasa9-species.js', 'NASA9_ALL_SPECIES', ' for every neutral gaseous species',
          dict(sorted(data.items(), key=lambda item: item[0].lower())), False)


if __name__ == '__main__':
    main()
